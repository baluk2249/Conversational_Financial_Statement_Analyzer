"""Backend protocols that keep agent logic independent of storage vendors."""

from __future__ import annotations

from typing import Protocol, Sequence

from models.schemas import ComputedMetric, DocumentChunk, FinancialFact, RedFlagResult, TrendResult


class StructuredFinancialStore(Protocol):
    def add_fact(self, fact: FinancialFact) -> None: ...
    def add_computed_metric(self, metric: ComputedMetric) -> None: ...
    def add_trend(self, trend: TrendResult) -> None: ...
    def add_red_flag(self, flag: RedFlagResult) -> None: ...
    def get_fact(self, company_id: str, metric: str, period: str | None = None, statement_type: str | None = None) -> FinancialFact | None: ...
    def get_facts(self, company_id: str, metrics: Sequence[str], periods: Sequence[str] | None = None, statement_type: str | None = None) -> list[FinancialFact]: ...
    def get_computed_metric(self, company_id: str, metric: str, period: str | None = None) -> ComputedMetric | None: ...
    def get_computed_metrics(self, company_id: str, metrics: Sequence[str] | None = None, periods: Sequence[str] | None = None) -> list[ComputedMetric]: ...
    def get_trends(self, company_id: str, metrics: Sequence[str] | None = None, periods: Sequence[str] | None = None) -> list[TrendResult]: ...
    def get_red_flags(self, company_id: str, periods: Sequence[str] | None = None) -> list[RedFlagResult]: ...


class NarrativeVectorStore(Protocol):
    def add_chunks(self, chunks: Sequence[DocumentChunk]) -> None: ...
    def search(self, query: str, company_id: str, period: str | None = None, document_type: str | None = None, top_k: int = 5) -> list[DocumentChunk]: ...


class TrendAndRedFlagProvider(Protocol):
    def get_trends(self, company_id: str, metrics: Sequence[str] | None = None, periods: Sequence[str] | None = None) -> list[TrendResult]: ...
    def get_red_flags(self, company_id: str, periods: Sequence[str] | None = None) -> list[RedFlagResult]: ...